from fastapi import APIRouter
from db import get_connection

router = APIRouter()

@router.get("/shortage-report")
def get_shortage_report():
    """Queries Shortage_Alert_View (<75%)."""
    conn = get_connection()
    cursor = conn.cursor(dictionary=True)
    try:
        cursor.execute("SELECT * FROM Shortage_Alert_View ORDER BY Attendance_Pct ASC;")
        records = cursor.fetchall()
        for r in records:
            r["Attendance_Pct"] = float(r["Attendance_Pct"])
        return records
    finally:
        cursor.close()
        conn.close()

@router.get("/audit-log")
def get_audit_log(limit: int = 50):
    """Retrieves immutable audit trail generated by row-level triggers."""
    conn = get_connection()
    cursor = conn.cursor(dictionary=True)
    try:
        query = """
            SELECT a.Audit_ID, p.Full_Name AS Student_Name, s.Enrollment_No,
                   a.Session_ID, a.Old_Status, a.New_Status,
                   a.Changed_By, a.Changed_At, a.Change_Reason
            FROM ATTENDANCE_AUDIT a
            JOIN STUDENT s ON a.Student_ID = s.Person_ID
            JOIN PERSON p ON s.Person_ID = p.Person_ID
            ORDER BY a.Changed_At DESC
            LIMIT %s;
        """
        cursor.execute(query, (limit,))
        records = cursor.fetchall()
        for r in records:
            r["Changed_At"] = str(r["Changed_At"])
        return records
    finally:
        cursor.close()
        conn.close()

@router.post("/monthly-digest")
def run_monthly_digest(month: int = 11, year: int = 2026):
    """Executes database cursor procedure GenerateMonthlyDigest."""
    conn = get_connection()
    cursor = conn.cursor(dictionary=True)
    try:
        cursor.callproc("GenerateMonthlyDigest", [month, year])
        digest_results = []
        for result in cursor.stored_results():
            rows = result.fetchall()
            for row in rows:
                row["Average_Attendance_Pct"] = float(row["Average_Attendance_Pct"])
            digest_results.extend(rows)
        return digest_results
    finally:
        cursor.close()
        conn.close()

